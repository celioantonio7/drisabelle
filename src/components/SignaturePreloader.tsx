export default function SignaturePreloader() {
  const [fading, setFading] = useState(false)
  const [done, setDone] = useState(false)

  const dismiss = () => {
    setFading(true)
    window.setTimeout(() => {
      document.body.style.overflow = ''
      document.documentElement.style.overflow = ''
      setDone(true)
      window.setTimeout(() => ScrollTrigger.refresh(), 60)
    }, 350)
  }

  useEffect(() => {
    if (done) {
      document.body.style.overflow = ''
      document.documentElement.style.overflow = ''
      return
    }

    document.body.style.overflow = 'hidden'
    document.documentElement.style.overflow = 'hidden'

    const t1 = window.setTimeout(() => setFading(true), 1800)
    const t2 = window.setTimeout(() => {
      document.body.style.overflow = ''
      document.documentElement.style.overflow = ''
      setDone(true)
      window.setTimeout(() => ScrollTrigger.refresh(), 60)
    }, 2300)

    return () => {
      document.body.style.overflow = ''
      document.documentElement.style.overflow = ''
      window.clearTimeout(t1)
      window.clearTimeout(t2)
    }
  }, [done])

  if (done) return null

  return (
    <div
      className={`sig-preloader-backdrop ${fading ? 'is-fading' : ''}`}
      aria-hidden="true"
      onClick={dismiss}
      onTouchStart={dismiss}
      style={{ cursor: 'pointer' }}
    >
      <div className="sig-preloader-center">
        <svg
          className="sig-preloader-svg"
          viewBox="0 0 680 175"
          fill="none"
          xmlns="http://www.w3.org/2000/svg"
        >
          <defs>
            <linearGradient id="sigGoldGrad" x1="0%" y1="0%" x2="100%" y2="0%">
              <stop offset="0%" stopColor="#0b192c" />
              <stop offset="55%" stopColor="#0056d6" />
              <stop offset="100%" stopColor="#b8860b" />
            </linearGradient>
          </defs>

          {/* Letter-by-letter pen stroke drawing (like componentry.dev/docs/components/signature) */}
          <g className="sig-letters-group">
            {SIGNATURE_GLYPHS.map((item, idx) => (
              <path
                key={idx}
                d={item.d}
                pathLength={1}
                className="sig-letter-path"
                style={{ ['--char-idx' as string]: idx }}
              />
            ))}
          </g>

          {/* Final calligraphic underline flourish after last letter */}
          <path
            className="sig-preloader-flourish"
            pathLength={1}
            d="M 110 128 C 220 112, 390 142, 555 114 C 585 108, 565 98, 520 105 C 445 116, 310 132, 185 136"
            stroke="url(#sigGoldGrad)"
            strokeWidth="2.4"
            strokeLinecap="round"
            fill="none"
          />
        </svg>

        <span className="sig-preloader-sub">
          ODONTOLOGIA ESTÉTICA &amp; HARMONIZAÇÃO FACIAL
        </span>
      </div>
    </div>
  )
}
